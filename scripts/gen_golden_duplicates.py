"""
Freeze the duplicate detector's verdicts over the synthetic corpus.

Every track is run against all the others, so the fixtures capture what the
detector does NOT match as well as what it does - false positives are the
expensive failure here, since a wrong match hides a set you would have kept.

Two fixtures are produced:
  pairs   - is_probable_duplicate() for every same-artist pair, the predicate
  matches - find_candidates() per track, the whole pipeline

Each track's artist is its `manual` correction if it has one, else what
core/artists.py resolves - as track_artists reads in a real library.
Regenerate only when a behaviour change is intended, and review the diff.
"""

import json
from itertools import combinations

# Importing gen_golden_artists also puts src/ on the path.
from gen_golden_artists import GOLDEN, load_corpus, resolution_config

from core import artists, duplicates  # noqa: E402
from core.models import TrackRef  # noqa: E402


def stored_rows(corpus: dict) -> list:
    cfg = resolution_config(corpus)
    return [
        {
            "track_id": t["id"],
            "artist": t["uploader"],      # the uploader, as the fixture names it
            "title": t["title"],
            "real_artists": t.get("manual")
                            or artists.resolve(t["uploader"], t["title"], cfg),
            "duration_ms": round(t["minutes"] * 60000),
            "duplicate_of": t.get("duplicate_of", ""),
        }
        for t in corpus["tracks"]
    ]


def ref(row: dict, duplicate_of: str = "") -> TrackRef:
    return TrackRef(track_id=row["track_id"], title=row["title"],
                    artist=row["real_artists"], uploader=row["artist"],
                    duration_ms=row["duration_ms"], duplicate_of=duplicate_of)


def judged_pairs(rows: list, qualifiers: frozenset) -> list:
    """The predicate over every pair that shares an artist."""
    by_artist: dict = {}
    for r in rows:
        by_artist.setdefault(duplicates.normalize_artists(r["real_artists"]), []).append(r)
    pairs = []
    for key, group in by_artist.items():
        if not key:
            continue
        for a, b in combinations(group, 2):
            pairs.append({
                "a": {k: a[k] for k in ("title", "real_artists", "duration_ms")},
                "b": {k: b[k] for k in ("title", "real_artists", "duration_ms")},
                "expected": duplicates.is_probable_duplicate(ref(a), ref(b), qualifiers),
            })
    return pairs


def pipeline_matches(rows: list, cfg: duplicates.DuplicateConfig) -> list:
    """find_candidates() for each track against all the others."""
    stored = [ref(r, r["duplicate_of"]) for r in rows]
    matches = []
    for r in rows:
        others = [t for t in stored if t.track_id != r["track_id"]]
        found = duplicates.find_candidates(ref(r), others, cfg)
        matches.append({
            "track_id": r["track_id"], "uploader": r["artist"], "title": r["title"],
            "real_artists": r["real_artists"], "duration_ms": r["duration_ms"],
            "matches": sorted([m.existing.track_id, m.new_is_official,
                               m.existing_is_official] for m in found),
        })
    return matches


def main() -> None:
    corpus = load_corpus()
    c = corpus["config"]
    cfg = duplicates.DuplicateConfig(
        location_qualifiers=frozenset(q.lower() for q in c["location_qualifiers"]),
        repost_accounts=frozenset(a.lower() for a in c["repost_accounts"]),
    )
    rows = stored_rows(corpus)
    pairs = judged_pairs(rows, cfg.location_qualifiers)
    matches = pipeline_matches(rows, cfg)

    out = GOLDEN / "duplicates.json"
    with open(out, "w", encoding="utf-8") as f:
        json.dump({
            "note": "Generated by scripts/gen_golden_duplicates.py from "
                    "tests/golden/corpus.json.",
            "config": {"repost_accounts": c["repost_accounts"],
                       "location_qualifiers": c["location_qualifiers"]},
            "rows": rows,
            "pairs": pairs,
            "matches": matches,
        }, f, indent=1, ensure_ascii=False)

    hit = sum(1 for p in pairs if p["expected"])
    with_match = sum(1 for m in matches if m["matches"])
    print(f"{len(pairs)} same-artist pairs, {hit} judged duplicates")
    print(f"{len(matches)} tracks, {with_match} with at least one candidate")
    print(f"-> {out}")


if __name__ == "__main__":
    main()
