"""
Freeze src/core/artists.py's output over the synthetic corpus.

tests/golden/corpus.json holds invented uploads chosen to walk every branch of
the resolver: the uploader, a b2b in the account name, a b2b in the title,
repost titles with and without separators, event stripping, aliases, casing
and the parse failures. The fixtures detect UNINTENDED change. Regenerate only
when a behaviour change is intended, and review
`git diff tests/golden/artists.json` before accepting it.

Public: load_corpus, resolution_config (gen_golden_duplicates.py reuses both)
Imports core/ only - never data/, so no database is read.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
from core import artists  # noqa: E402  the implementation under test

GOLDEN = ROOT / "tests" / "golden"


def load_corpus() -> dict:
    return json.loads((GOLDEN / "corpus.json").read_text(encoding="utf-8"))


def resolution_config(corpus: dict) -> artists.ResolutionConfig:
    """
    The same object data/settings.py builds from a database. The casing map
    comes from `established_artists`, standing in for what a library holds.
    """
    c = corpus["config"]
    return artists.ResolutionConfig(
        aliases=c["aliases"],
        repost_accounts=frozenset(a.lower() for a in c["repost_accounts"]),
        known_events=tuple(c["known_events"]),
        canonical_casing=artists.build_canonical_casing(
            corpus["established_artists"]),
    )


def main() -> None:
    corpus = load_corpus()
    cfg = resolution_config(corpus)
    cases = [
        {"uploader": t["uploader"], "title": t["title"],
         "expected": artists.resolve(t["uploader"], t["title"], cfg)}
        for t in corpus["tracks"]
    ]
    out = GOLDEN / "artists.json"
    with open(out, "w", encoding="utf-8") as f:
        json.dump({
            "note": "Generated by scripts/gen_golden_artists.py from "
                    "tests/golden/corpus.json.",
            "config": {
                "aliases": corpus["config"]["aliases"],
                # Deliberately NOT sorted: core/ must strip events longest-first
                # whatever order the list arrives in.
                "repost_accounts": corpus["config"]["repost_accounts"],
                "known_events": corpus["config"]["known_events"],
            },
            "canonical_casing": dict(cfg.canonical_casing),
            "cases": cases,
        }, f, indent=1, ensure_ascii=False)

    distinct = len({c["expected"] for c in cases})
    print(f"{len(cases)} cases -> {out}")
    print(f"{distinct} distinct results, {len(cfg.canonical_casing)} casing entries")


if __name__ == "__main__":
    main()
